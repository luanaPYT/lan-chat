class Translator:
    def __init__(self, lang="en"):
        self.lang = lang if lang in TRANSLATIONS else "en"

    def t(self, key, **kwargs):
        msg = TRANSLATIONS[self.lang].get(
            key, TRANSLATIONS["en"].get(key, key)
        )
        return msg.format(**kwargs)